class SignalVectorGenerator:
    r"""A class that generates signal vectors for a given set of magnetic (H) field. 

    Note that h_field should have 3 dimensions, whereof 
    - the first dimension (axis=0) equals the number of channels, 
    - the second dimension (axis=1) equals the number of pixels,
    - the third dimension (axis=2)  is 3, corresponding to vector's x, y, and z components.

    Construction is based on Lorentz Reciprocity Theorem. Assume the magnetic moment can be written as \(\mathbf{M}^+ = [1, \mathrm{j}, 0]\), which can be equivalently expressed in a complex-number form \(m^+ = 1+j\). Using the vector form, the signal of channel \(l\) should equal \(c \mathbf{M}^+ \cdot H_l\), where c is a constant for a particular array geometry, \(H_l\) is the magnetic field generated by channel \(l\) when unit current is injected to channel \(l\) and every other channel is open-circuited. All signals from each channel form a vector \(\mathbf{u} = \left[ \mathbf{M}^+ \cdot H_1, \mathbf{M}^+ \cdot H_2, \dots, \mathbf{M}^+ \cdot H_{N-1} \right]^\mathsf{T}\). Then \(\mathbf{u}\) is normalized.
    """
    def __init__(self, h_field: np.ndarray[np.complexfloating], positions: np.ndarray[np.number] = None, in_ROI: np.ndarray[np.bool_] = None) -> None:
        """Constructs a signal vector generator class. The function only keeps entries of h_field and positions that are within the region of interest. Whether h_field and positions are in the region of interest is specified by in_ROI.

        Args:
            h_field (np.ndarray): Magnetic field maps of all channels, stacked in a three-dimensional numpy array of size (# of channels, # of imaging pixels, 3). Other dimensions allowed are (# of channels, 3) when # of imaging pixels == 1, (# of imaging pixels, 3) when # of channels == 1, (3,) when # of channels == 1 and # of imaging pixels == 1. 
            positions (np.ndarray, optional): the coordinates of points where H field is taken. It must have the dimensions (# of imaging pixels, 3). Another dimension allowed is (3,) when # of imaging pixels == 1. When positions is set None, no information of point coordinates is saved in the instantiated class. Defaults to None. 
            in_ROI (np.ndarray, optional): an array mask of whether a corresponding entry is in the region of interest (ROI). It must have the dimensions (# of imaging pixels,). If an entry is True, it means the corresponding entry of h_field and positions in terms of imaging pixels is within the region of interest. If an entry is False, it means the corresponding entry of h_field and positions in terms of imaging pixels is outside the region of interest. When in_ROI is not None, only the entries of h_field and positions corresponding to True entries of in_ROI are saved in the instantiated class. When in_ROI is None, all h_field and positions are saved in the instantiated class, i.e., the effect is the same as setting in_ROI = np.array([True, True, True, ..., True]). Defaults to None.
        """
        if h_field is None or h_field.size == 0:
            raise ValueError("h_field cannot be None or empty")
        if h_field.size < 3 or np.size(h_field, -1) != 3:
            raise ValueError("corrupted h_field")
        if positions is not None:
            if np.ndim(positions) >= 3 or np.ndim(positions) == 0:
                raise ValueError("positions must be one- or two-dimensional")
            if np.size(positions, -1) != 3:
                raise ValueError("Corrupted point coordinates")
        match np.ndim(h_field):
            # Maybe this piece of code needs inspection
            case 3:  # Three-dimensional
                if positions is not None:
                    if (np.ndim(positions) == 2 and np.size(positions, 0) != np.size(h_field, 1)) or \
                        (np.ndim(positions) == 1 and 1 != np.size(h_field, 1)):
                        raise ValueError("number of points at which H field is taken does not equal number of point positions")
            case 2: # Two-dimensional
                if positions is not None:
                    if (np.ndim(positions) == 2 and np.size(positions, 0) != np.size(h_field, 0)) or \
                        (np.ndim(positions) == 1 and 1 != np.size(h_field, 0)):
                        raise ValueError("number of points at which H field is taken does not equal number of point positions")
            case 1: # One-dimensional. There is only one H field vector
                if positions is not None:
                    if np.ndim(positions) != 1 or (np.ndim(positions) == 2 and np.size(positions, 0) != 1):
                        raise ValueError("number of points at which H field is taken does not equal number of point positions")
            case _:
                raise ValueError("h_field has wrong dimensions")
        
        self._h_field: np.ndarray[np.complexfloating] = None
        self._position: np.ndarray[np.number] = None
        if in_ROI is not None:
            self._h_field = np.copy(h_field[:, in_ROI, :])
            if positions is not None:
                self._position = np.copy(positions[in_ROI, :])
        else:
            self._h_field = np.copy(h_field)
            if positions is not None:
                self._position = np.copy(positions)
        self._last_signal_vectors: np.ndarray[np.complexfloating] = None

    def __eq__(self, value: object) -> bool:
        if type(self) != type(value):  
            return False
        if np.ndim(self._h_field) != np.ndim(value._h_field) or np.shape(self._h_field) != np.shape(value._h_field) or (self._h_field.dtype != value._h_field.dtype) \
            or not np.allclose(self._h_field, value._h_field):
            return False
        # self._position is optional, so need additional check
        if (self._position is None) ^ (value._position is None):
            return False
        if self._position is not None and value._position is not None: 
            if np.ndim(self._position) != np.ndim(value._position) or np.shape(self._position) != np.shape(value._position) or \
                (self._position.dtype != value._position.dtype) or not np.allclose(self._position, value._position):
                return False
        # self._position is optional, so needs additional check
        if (self._last_signal_vectors is None) ^ (value._last_signal_vectors is None):
            return False
        if self._last_signal_vectors is not None and value._last_signal_vectors is not None:
            if np.ndim(self._last_signal_vectors) != np.ndim(value._last_signal_vectors) or np.shape(self._last_signal_vectors) != np.shape(value._last_signal_vectors) \
                or (self._last_signal_vectors.dtype != value._last_signal_vectors.dtype) or not np.allclose(self._last_signal_vectors, value._last_signal_vectors):
                return False
        return True
    
    # H field getter. The class should be immutable; the attribute cannot be re-set.
    @property
    def h_field(self):
        """The H field stored inside the class. This option always returns a copy.

        Returns:
            _type_: the H field stored inside the class. Always returns a copy.
        """
        return np.copy(self._h_field)
    
    @property
    def last_signal_vectors(self):
        """The signal vectors generated last time.

        Returns:
            _type_: the signal vectors generated last time. The return is a copy of the internal data of the class.
        """
        return np.copy(self._last_signal_vectors)
    
    @staticmethod
    def from_files(h_file_names: abc.Iterable[str], filter_ROI: Callable[[np.ndarray, np.ndarray], np.ndarray] = None) -> "SignalVectorGenerator":
        """Generates a SignalVectorGenerator class from a list of HDF5 files. All the HDF5 files can have the same number of entries or different numbers of entries. If the HDF5 files have different numbers of entries, filter_ROI must be given so that filtered field or point coordinate data have the same number of entries.

        Args:
            h_file_names (abc.Iterable[str]): a list of HDF5 files. The files should contain keys "Positions" and "H-field". All HDF5 files must have the same set of position coordinates.
            filter_ROI (function): a function that grabs the region of interest. The function must accept two np.ndarray arguments, and produce a one-dimensional numpy array of booleans. This function applies to each file in h_file_names. It does not act on the aggregate of all data.
            If filter_ROI is None, no filter of region of interest is applied, and all results will be saved in memory. Defaults to None.

        Returns:
            SignalVectorGenerator: an instantiated SignalVectorGenerator class. If filter_ROI is None, no filter of region of interest is applied, and all results will be saved in memory. If filter_ROI is not None, the class only keeps entries of which the corresponding filter_ROI results are True.
        """
        first_pos, first_h_field = SignalVectorGenerator.__read_one_file(h_file_names[0])
        first_pos_filtered: np.ndarray[np.number] = first_pos
        first_h_field_filtered: np.ndarray[np.complexfloating] = first_h_field
        if filter_ROI is not None:
            first_filter: np.ndarray[np.bool_] = filter_ROI(first_pos, first_h_field)
            first_pos_filtered = first_pos[first_filter]  # Works for one- and two-dimensional arrays
            first_h_field_filtered = first_h_field[first_filter]  # Works for one- and two-dimensional arrays
            assert first_pos_filtered.shape == first_h_field_filtered.shape  # Sanity check

        all_h_field_filtered: np.ndarray[np.complexfloating] = first_h_field_filtered
        if len(h_file_names) > 1:
            all_h_field_filtered = np.zeros((len(h_file_names), *np.shape(first_h_field_filtered)), dtype=np.complex_)
            all_h_field_filtered[0, ...] = first_h_field_filtered
        for iter_n, h_file in enumerate(h_file_names[1:]):  # if h_file_names just has one element then the loop won't execute
            current_pos, current_h_field = SignalVectorGenerator.__read_one_file(h_file)
            current_pos_filtered: np.ndarray[np.bool_] = current_pos
            current_h_field_filtered: np.ndarray[np.complexfloating] = current_h_field
            if filter_ROI is not None:
                current_filter: np.ndarray[np.bool_] = filter_ROI(current_pos, current_h_field)
                current_pos_filtered = current_pos[current_filter]  # Works for one- and two-dimensional arrays
                current_h_field_filtered = current_h_field[current_filter]  # Works for one- and two-dimensional arrays
            if first_pos_filtered.shape != current_pos_filtered.shape:
                raise ValueError("The point positions do not have the same size")
            if not np.allclose(first_pos_filtered, current_pos_filtered):
                raise ValueError("The point positions are not the same")
            assert current_h_field_filtered.shape == first_h_field_filtered.shape  # Sanity check
            all_h_field_filtered[iter_n + 1, ...] = current_h_field_filtered
        return SignalVectorGenerator(all_h_field_filtered, first_pos_filtered, None)
        
    @staticmethod
    def __read_one_file(h_file_name: str) -> tuple[np.ndarray[np.number], np.ndarray[np.complexfloating]]:
        """Reads one HDF5 file and returns the positional coordinates and the H field in complex value. This function uses h5py module. H5PY reads an HDF5 file as a structured numpy array. This function converts the structured arrays into unstructured arrays.

        Args:
            h_file_name (str): the HDF5 file that contains positional coordinates and the H field data. 

        Returns:
            tuple[np.ndarray[np.number], np.ndarray[np.complexfloating]]: the positional coordinates and the H field in complex value
        """
        file_contents = h5py.File(h_file_name, "r")
        h_field = file_contents["H-Field"]
        h_pos = file_contents["Position"]
        h_pos_np_unstructured_array: np.ndarray = recfunctions.structured_to_unstructured(h_pos[...]) # Create an array view with [...]. Refer to https://numpy.org/doc/stable/user/basics.copies.html#view
        # Dimensional check
        if h_field.size != h_pos.size:
            raise ValueError("Number of points do not match number of field vectors")
        if (np.ndim(h_pos_np_unstructured_array) == 1 and np.size(h_pos_np_unstructured_array) != 3) or \
            (np.ndim(h_pos_np_unstructured_array) == 2 and np.size(h_pos_np_unstructured_array, 1) != 3):
            raise ValueError("Postion vectors are not three-dimensional")
        if np.ndim(h_pos_np_unstructured_array) > 2 or np.ndim(h_pos_np_unstructured_array) == 0:
            raise ValueError("Not a valid postion vector array")
        h_field_np_unstructured_array = recfunctions.structured_to_unstructured(h_field[...]) # Create an array view with [...]. Refer to https://numpy.org/doc/stable/user/basics.copies.html#view
        # Dimensional check
        if (np.ndim(h_field_np_unstructured_array) == 1 and np.size(h_field_np_unstructured_array) != 6) or \
            (np.ndim(h_field_np_unstructured_array) == 2 and np.size(h_field_np_unstructured_array, 1) != 6):
            raise ValueError("Field vectors are not three-dimensional")
        if np.ndim(h_field_np_unstructured_array) > 2 or np.ndim(h_field_np_unstructured_array) == 0:
            raise ValueError("Not a valid field vector array")
        h_field_complex = h_field_np_unstructured_array[:, 0:6:2] + 1j * h_field_np_unstructured_array[:, 1:6:2]
        assert np.ndim(h_pos_np_unstructured_array) == np.ndim(h_field_complex)  # Sanity check
        assert np.size(h_pos_np_unstructured_array) == np.size(h_field_complex) # Sanity check
        del file_contents
        return h_pos_np_unstructured_array, h_field_complex
    
