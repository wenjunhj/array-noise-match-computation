    def SNR_map(self, core_39: np.ndarray[np.number]) -> np.ndarray[np.floating]:
        """Generates one or more SNR maps from signal vectors and (39) cores. For intraclass use only.

        Args:
            self._signal_vectors (np.ndarray): signal vectors assembled in an array, of which the dimensions are (# of channels, # of pixels)
            core_39 (np.ndarray): core (39). It can be one square matrix of size (# of channels, # of channels), or a three-dimensional matrix of size (# of different cores, # of channels, # of channels).

        Raises: 
            ValueError: when core_39's dimenions is neither 2 nor 3.

        Returns:
            np.ndarray: one or more SNR maps.
        """
        usH_C: np.ndarray[np.number] = None
        usH_C_us: np.ndarray[np.number] = None
        if np.ndim(core_39) == 2:
            usH_C = self._signal_vectors.conj().T @ core_39
            usH_C_us = np.sum(usH_C * self._signal_vectors.T, axis=1)  # Get only diagonal elements. https://stackoverflow.com/questions/14758283/is-there-a-numpy-scipy-dot-product-calculating-only-the-diagonal-entries-of-the
            assert np.size(usH_C_us, 0) == np.size(self._signal_vectors, 1)  # Just for sanity check
        elif np.ndim(core_39) == 3:
            usH_C = np.dot(self._signal_vectors.conj().T, core_39)
            # The line above can also be written as usH_C = np.tensordot(self._signal_vectors.conj().T, core_39, (1, 1))
            # np.dot() works because self._signal_vectors has only two dimensions. If self._signal_vectors were three-dimensional then the line above won't work.
            # Wang Wenjun confirmed the above sentence is right on 2024-09-07.
            # usH_C's dimensions are (# of pixels, # of different cores, # of channels).
            usH_C_axis_moved = np.moveaxis(usH_C, 1, 0)
            # Change the dimensions to (# of different cores, # of pixels, # of channels)
            # us_expanded = np.tile(self._signal_vectors.T, (usH_C_axis_moved.shape[0], 1, 1))  # No need
            usH_C_us = np.sum(usH_C_axis_moved * self._signal_vectors.T, axis=-1)
            # No need to expand signal vectors to shape (# of different cores, # of pixels, # of channels). Numpy will do broadcasting automatically: https://numpy.org/doc/stable/user/basics.broadcasting.html
            # Wang Wenjun confirmed the above sentence is right on 2024-09-07.
            # Then sum along the last axis, i.e., # of channels. This only takes the diagonal elements on each intersection along axis=0, which is what we need.
            # usH_C_us's dimensions are (# of different cores, # of pixels)
            assert np.size(usH_C_us, 1) == np.size(self._signal_vectors, 1) and np.size(usH_C_us, 0) == np.size(core_39, 0)
            # number of pixels == number of pixels and number of different cores == number of different cores. For sanity check.
        else:
            raise ValueError("core_39's dimension is neither 2 nor 3. Unsupported.")
        
        assert np.allclose(np.imag(usH_C_us), 0.)  # Mathematically the imaginary part must be 0. For sanity check.
        return np.real(usH_C_us)
    
    def __parse_coordinates(self) -> None:
        """Parse the point coordinates the user put in. Generates x_min, x_max, y_min, y_max, z_min, z_max, and x_step, y_step, z_step. This function assumes the positions the user passes into the SNRMapper class are already on a rectangular grid (but does not have to form a full rectangular region).

        Raises:
            ValueError: error if there exists duplicates in point_coordinates
        """
        coordinate_unique, coordinate_count = np.unique(self._point_coordinates, axis=0, return_counts=True)
        if np.any(coordinate_count > 1):
            raise ValueError("Duplicates in coordinates found. The duplicates are\n{}".format(coordinate_unique[coordinate_count > 1]))
        self._x_min, self._y_min, self._z_min = np.min(self._point_coordinates, 0)
        self._x_max, self._y_max, self._z_max = np.max(self._point_coordinates, 0)
        delta_xyz = np.abs(np.diff(self._point_coordinates, axis=0))
        delta_x_with_0, delta_y_with_0, delta_z_with_0 = delta_xyz.T
        delta_x_without_0: np.ndarray = delta_x_with_0[np.nonzero(delta_x_with_0)]
        delta_y_without_0: np.ndarray = delta_y_with_0[np.nonzero(delta_y_with_0)]
        delta_z_without_0: np.ndarray = delta_z_with_0[np.nonzero(delta_z_with_0)]
        self._x_step, self._y_step, self._z_step = 0.0, 0.0, 0.0
        if delta_x_without_0.size != 0:
            self._x_step = delta_x_without_0.min()
        if delta_y_without_0.size != 0:
            self._y_step = delta_y_without_0.min()
        if delta_z_without_0.size != 0:
            self._z_step = delta_z_without_0.min()
    
    def put_map_on_regular_grid(self, point_function_vector: Union["SNRMapper.MapSelect", np.ndarray[np.number]], point_admissibility_mask: np.ndarray[np.bool_]=None, anchor_value: np.integer | np.floating = 1, return_regularized_coordinates: bool=False) -> tuple[np.ndarray[np.floating], np.ndarray[np.floating], np.ndarray[np.floating], np.ndarray[np.floating]] | np.ndarray[np.floating]:
        """The SNRMapper class only stores pixel (voxel) positions and their corresponding SNR values. They are not ready for typical matplotlib plotters, e.g., imshow(), contourf(). This function generates a full rectangular grid of a rectangular region puts SNR values at their corresponding places. This function only works when the positions the user passes into the SNRMapper class are already on a rectangular grid (but does not have to form a full rectangular region).

        Args:
            point_function_vector: any scalar value of point functions. The user can choose a pre-defined map as listed in the MapSelect enumerator class, or pass a point function vector him/herself. If the user passes in a point function vector, then the vector will be flattened.
            point_admissibility_mask (np.ndarray, optional): a mask of whether the ultimate SNR is reachable at one point. A True entry means the ultimate SNR is reachable there. A False entry means the ultimate SNR is unreachable there. The admissibility mask must be a vector of the same size as the position vector the user passes to the class constructor. Default to None, meaning there is no mask.
            anchor_value (np.integer | np.floating, optional): 
            return_regularized_coordinates (bool, optional): if true, the function returns a rectangular grid generated by numpy.meshgrid. Default to false.

        Raises:
            ValueError: when point_function_vector does not have the same number of elements as of point_coordinates 

        Returns:
            tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray] | np.ndarray: returns values if return_regularized_coordinates = False; returns (x grid, y grid, z grid, values) if return_regularized_coordinates = True
        """
        if point_function_vector is None:
            raise ValueError("point_function_vector cannot be None")
        if anchor_value <= 0:
            raise ValueError("anchor_value cannot be negative or zero")
        function_vector: np.ndarray[np.number] = None
        if isinstance(point_function_vector, SNRMapper.MapSelect):
            match point_function_vector:
                case SNRMapper.MapSelect.REF_SNR:
                    function_vector = self.ref_SNR_map  # This will return a copy of the internal class so the array inside the class remains safe
                case SNRMapper.MapSelect.SECOND_REF_SNR:
                    function_vector = self.second_ref_SNR_map # This will return a copy of the internal class so the array inside the class remains safe
        elif isinstance(point_function_vector, np.ndarray):  # np.ndarray
            if np.size(point_function_vector) != np.size(self._point_coordinates, 0):
                raise ValueError("point_function_vector does not have the same number of elements as of point_coordinates")
            function_vector = point_function_vector.flatten()
        else:
            raise ValueError("Invalid argument for point_function_vector")
        if function_vector is None:
            raise ValueError("the selected function does not yet exist")
        if point_admissibility_mask is not None:
            function_vector[np.logical_not(point_admissibility_mask)] = np.nan
        n_points_x: np.int_ = 1
        n_points_y: np.int_ = 1
        n_points_z: np.int_ = 1
        x_grid: np.ndarray[np.floating] = None
        y_grid: np.ndarray[np.floating] = None
        z_grid: np.ndarray[np.floating] = None
        x_sequence: np.ndarray[np.floating] | np.floating = self._x_max
        y_sequence: np.ndarray[np.floating] | np.floating = self._y_max
        z_sequence: np.ndarray[np.floating] | np.floating = self._z_max
        xyz_indices: np.ndarray[np.int_] = np.zeros(self._point_coordinates.shape, dtype=np.int_)
        if not np.isclose(self._x_step, 0.0):
            n_points_x = np.round(1 + (self._x_max - self._x_min) / self._x_step).astype(np.int_)
            xyz_indices[:, 0] = ((self._point_coordinates[:, 0] - self._x_min) / self._x_step).astype(np.int_)
            if return_regularized_coordinates:
                x_sequence = np.arange(start=self._x_min, stop=self._x_max + self._x_step, step=self._x_step, dtype=np.float_)
        if not np.isclose(self._y_step, 0.0):
            n_points_y = np.round(1 + (self._y_max - self._y_min) / self._y_step).astype(np.int_)
            xyz_indices[:, 1] = ((self._point_coordinates[:, 1] - self._y_min) / self._y_step).astype(np.int_)
            if return_regularized_coordinates:
                y_sequence = np.arange(start=self._y_min, stop=self._y_max + self._y_step, step=self._y_step, dtype=np.float_)
        if not np.isclose(self._z_step, 0.0):
            n_points_z = np.round(1 + (self._z_max - self._z_min) / self._z_step).astype(np.int_)
            xyz_indices[:, 2] = ((self._point_coordinates[:, 2] - self._z_min) / self._z_step).astype(np.int_)
            if return_regularized_coordinates:
                z_sequence = np.arange(start=self._z_min, stop=self._z_max + self._z_step, step=self._z_step, dtype=np.float_)
        map_3d: np.ndarray[np.float_] = np.full((n_points_x, n_points_y, n_points_z), np.nan, dtype=np.float_)
        # Then fill into map3d
        map_3d[*(xyz_indices.T)] = function_vector  # Works --Jepsen Rasmus, Wang Wenjun, on 2024-09-06
        if not np.isclose(anchor_value, 0) and not np.isclose(anchor_value, 1):
            map_3d = map_3d / anchor_value
        if return_regularized_coordinates:
            x_grid, y_grid, z_grid = np.meshgrid(x_sequence, y_sequence, z_sequence)
            return x_grid, y_grid, z_grid, map_3d
        else:
            return map_3d

    def relative_SNR_difference_between_refs(self, ref: RefSelect=__default_reference) -> np.ndarray[np.float_]:
        """The relative difference between two references

        Args:
            ref (SNRMapper.RefSelect, optional): the reference core. Defaults to RefSelect.FIRST_REFERENCE_CORE.

        Returns:
            np.ndarray[np.float_]: the relative difference between two references
        """
        if self._second_ref_SNR_map is None:
            raise ValueError("The second reference has not been set")
        match ref:
            case SNRMapper.RefSelect.FIRST_REFERENCE_CORE:
                return self._second_ref_SNR_map / self._ref_SNR_map - 1
            case SNRMapper.RefSelect.SECOND_REFERENCE_CORE:
                return self._ref_SNR_map / self._second_ref_SNR_map - 1

    def absolute_SNR_difference_between_refs(self, ref: RefSelect=__default_reference) -> np.ndarray[np.float_]:
        """The absolute difference between two references

        Args:
            ref (SNRMapper.RefSelect, optional): the reference core. Defaults to RefSelect.FIRST_REFERENCE_CORE.

        Returns:
            np.ndarray[np.float_]: the relative difference between two references
        """
        if self._second_ref_SNR_map is None:
            raise ValueError("The second reference has not been set")
        match ref:
            case SNRMapper.RefSelect.FIRST_REFERENCE_CORE:
                return self._second_ref_SNR_map - self._ref_SNR_map
            case SNRMapper.RefSelect.SECOND_REFERENCE_CORE:
                return self._ref_SNR_map - self._second_ref_SNR_map
            
    def SNR_ref_value(self, anchor_point: np.ndarray[np.number] | np.integer = np.ndarray([0, 0, 0]), ref: RefSelect=__default_reference) \
        -> tuple[np.number, np.number]:
        """Extracts the SNR value of a reference SNR map at a point.

        Args:
            anchor_point (np.ndarray[np.number] | np.integer, optional): The point at which SNR is taken. It can be either a one-dimensional numpy array indicating the point coordinates, or an integer, which is the index of the point in point_coordinates the user used to make the current SNRMapper class. Defaults to np.ndarray([0, 0, 0]).
            ref (SNRMapper.RefSelect, optional): _description_. Defaults to RefSelect.FIRST_REFERENCE_CORE.

        Returns:
            tuple[np.number, np.number]: The first element is the index of anchor_point. If anchor_point is an integer, this element is anchor_point. If anchor_point is a numpy array, this element is the index of the nearest point in point_coordinates, the argument for constructing the current SNRMapper class. The second element is the SNR at the anchor point.
        """
        snr_map: np.ndarray = None
        match ref:
            case SNRMapper.RefSelect.FIRST_REFERENCE_CORE:
                snr_map = self._ref_SNR_map
            case SNRMapper.RefSelect.SECOND_REFERENCE_CORE:
                snr_map = self._second_ref_SNR_map
        if snr_map is None:
            raise ValueError("The selected type of reference has not been set")
        nearest_position: np.integer = 0
        if isinstance(anchor_point, np.ndarray):
            if np.ndim(anchor_point) > 1 or np.size(anchor_point) != 3:
                raise ValueError("anchor_point is an invalid argument")
            # distance_sq: np.ndarray[np.number] | np.number = np.sum((self._point_coordinates - anchor_point[np.newaxis, ...]) ** 2, axis=1)
            # nearest_position = self.__find_nearest_position(distance_sq, 0.0)
            nearest_position, _ = SNRMapper.find_nearest_point(self._point_coordinates, anchor_point)
        elif isinstance(anchor_point, np.integer):
            nearest_position = anchor_point
        else:
            raise ValueError("anchor_point is neither a numpy.ndarray nor an integer")
        return nearest_position, snr_map[nearest_position]

