    def matZ_43_elements(self, signal_vectors: np.ndarray[np.number]) -> tuple[np.ndarray[np.number], np.ndarray[np.bool_]]:
        """Get diagonal elements of matrix [Z] defined in (43).

        Args:
            signal_vectors (np.ndarray): column signal vectors stacked horizontally as a matrix. Dimensions should be a tuple of (# of channels, # of voxels)

        Returns:
            tuple[np.ndarray, np.bool_]: a tuple of which the first element is all the diagonal elements of the [Z] matrix defined in (43), the second element is whether any element has a negative real part.
            The matrix elements are listed along axis=1.
        """
        #### Needs checking!!
        usH_A1: np.ndarray[np.number] = signal_vectors.conj().T @ self._inv_A  # @ is matrix multiplication 
        usH_A1Za: np.ndarray[np.number] = usH_A1 @ self._Za
        mat_Z_diag_elements: np.ndarray[np.number] = usH_A1Za / usH_A1
        contains_negative_element: np.ndarray[np.bool_] = np.any(np.real(mat_Z_diag_elements) < 0, -1)
        return mat_Z_diag_elements, contains_negative_element  
    
    def get_chunk_39(self, mat_D: np.ndarray[np.floating], matZ_diag: np.ndarray[np.number]) -> np.ndarray[np.number]:
        r"""The part between $\mathbf{U}_\mathrm{s}^\mathsf{H}$ and $\mathbf{U}_\mathrm{s}$ in (39), WITHOUT the inverse sign.

        Args:
            mat_D (np.ndarray): diagonal matrix [D] = [2 P_\mathrm{opt;\infty} / R_\mathrm{opt}]. Note it is tied to matZ_diag.
            matZ_diag (np.ndarray): a diagonal matrix [Z] defined in (43). 
            Both mat_D and matZ_diag can be 2- or 3-dimensional arrays, as long as they have the save dimension. When they are 3-dimensional arrays, the first axis (axis=0) should indicate pixel index.

        Returns:
            np.ndarray: the part between $\mathbf{U}_\mathrm{s}^\mathsf{H}$ and $\mathbf{U}_\mathrm{s}$ in (39), WITHOUT the inverse sign.
        """
        ### for np.ndim == 2 checking passed on 2024-09-05
        ### need to check np.ndim == 3
        if mat_D.shape != matZ_diag.shape:
            raise ValueError("matZ_diag and mat_D must have the same dimensions")
        matZa_Z: np.ndarray = self._Za - matZ_diag
        if np.ndim(matZa_Z) == 2:
            matB: np.ndarray = matZa_Z @ mat_D @ matZa_Z.conj().T  # Here might be problematic
            return self._A + matB  # Here dimensions may be incommensurate
        elif np.ndim(matZa_Z) == 3:
            product_1: np.ndarray = matZa_Z @ mat_D
            # Sum over axis=2 of (Za - Z) and axis=1 of [D]. This can also be written as np.matmul(matZa_Z, mat_D). We shall not use np.dot() or np.tensordot() here because the resulting array will be four-dimensional. The operation we want should treat both operands as stacks of matrices rather than tensors, so that the resulting array is still three-dimensional. The operation can be done by numpy.matmul(), whose shorthand notation is @. See https://numpy.org/doc/stable/reference/generated/numpy.matmul.html   ---Wang Wenjun, 2024-09-07
            matZa_Z_H: np.ndarray = np.swapaxes(matZa_Z.conj(), 1, 2)  # Get Hermitian transpose along the last two axes
            product_2: np.ndarray = product_1 @ matZa_Z_H  # Sum over axis=2 of product_1 and axis=1 of matZa_Z_H
            # A_tiled: np.ndarray = np.tile(self._A, (matZ_diag.shape[0], 1, 1)) # repeat A
            # There is no need to tile self._A because self._A will be broadcast, as long as the last two dimensions match. See https://numpy.org/doc/stable/user/basics.indexing.html  ---Wang Wenjun, 2024-09-07
            return self._A + product_2
        else:
            raise ValueError("matZ_diag and mat_D must be 2- or 3-dimensional arrays")

    def noise_match_core(self, inverse:bool=True) -> np.ndarray[np.complexfloating]:
        r"""Get the part between $\mathbf{U}_\mathrm{s}^\mathsf{H}$ and $\mathbf{U}_\mathrm{s}$ in (39) when each channel is optimally noise matched by individual.
        By default, the inverse sign is included uncless inverse == False

        Args:
            inverse (bool, optional): The inverse is NOT included if inverse == False. Defaults to True.

        Returns:
            np.ndarray: the part between $\mathbf{U}_\mathrm{s}^\mathsf{H}$ and $\mathbf{U}_\mathrm{s}$ in (39)
        """
        # Passed checking
        chunk_39 = self.get_chunk_39(self._diag_D_noise_match, self._diag_Za)
        if inverse:
            return linalg.inv(chunk_39)
        else:
            return chunk_39
        
    def signal_optimization_core(self, signal_vectors: np.ndarray[np.number], admissible_only: np.bool_=True, inverse: bool=True) \
        -> tuple[np.ndarray[np.number], np.ndarray[np.bool_]]:
        r"""Get the part between $\mathbf{U}_\mathrm{s}^\mathsf{H}$ and $\mathbf{U}_\mathrm{s}$ in (39) for a specific signal vector $\mathbf{U}_\mathrm{s}$. The function will also return a boolean array of admissibility that shows whether the corresponding signal_vector entry is admissible.
        The function has two switches. One admissible_only, so that only the admissible signal vectors are returned and saved inside the class. The other is inverse, which determines whether the (39) core has an inverse sign or not.

        Args:
            signal_vectors (np.ndarray[np.number]): the signal vectors for optimization, stacked in a two-dimensional array of shape (# of channels, # of vectors)
            admissible_only (np.bool_, optional): if set to True, only admissible signal vectors will be used to generate signal optimization cores. If set to False, all signal vectors will be used to generate signal optimization cores. Default to True. It is recommended to set admissible_only as True as it saves memory and computational power. A signal vector being admissible means all real parts of Z as calculated by (43) are positive.
            inverse_only (np.bool_, optional): if set to True, the resulting (39) core will include an inverse sign, i.e., the user will get (...)^{-1}. If set to False, the resulting (39) core will not include an inverse sign, i.e., the user will get (...)^1.

        Returns:
            tuple[np.ndarray[np.number], np.ndarray[np.bool_]]: The first element is all (39) cores. Whether they are admissible-only or they are returned regardless of admissibility depends on the admissible_only argument. The second element is an admissibility vector showing whether the corresponding entries of signal_vectors are admissible. If one entry is True, it means its corresponding entry of signal_vectors is admissible. If one entry is False, it means its corresponding entry of signal_vectors is inadmissible. The admissibility vector always has the same number of entries as signal_vectors. The admissibility vector may have different number of entries of (39) cores.
        """
        if np.size(signal_vectors) == 0:
            raise ValueError("signal_vectors is empty")
        if (np.ndim(signal_vectors) > 2):
            raise ValueError("signal_vectors has more than two dimensions")
        if np.size(signal_vectors, 0) != np.size(self._Za, -1):
            raise ValueError("signal_vectors has a different number of channels from impedance matrices'")
        matZ_diag_elements, need_negative_elements = self.matZ_43_elements(signal_vectors)  # matZ_diag_elements are taken along axis=1, i.e., row by row.
        n_channels: np.integer = np.size(signal_vectors, 0)
        admissibility: np.ndarray[np.bool_] = np.logical_not(need_negative_elements)
        self._last_signal_vectors_admissible_mask = admissibility.copy()
        self._last_signal_vectors = signal_vectors.copy() 
        self._last_diag_Z_elements = matZ_diag_elements # The class keeps all [Z]'s elements no matter they're admissble or not.
        matZ_diag_elements_for_computation: np.ndarray[np.number] = matZ_diag_elements
        signal_vectors_for_computation: np.ndarray[np.number] = signal_vectors
        if admissible_only:
            matZ_diag_elements_for_computation = matZ_diag_elements[admissibility, ...]
            signal_vectors_for_computation = signal_vectors[..., admissibility]  # This will always make an array two-dimensional
        if np.size(signal_vectors_for_computation) == 0:  # No signal vector left. Exit.
            return None, admissibility
        if np.ndim(signal_vectors_for_computation) == 1: # Just one signal vector
            matZ_diag: np.ndarray[np.complex_] = np.zeros((n_channels, n_channels), dtype=np.complex_)
            matD_diag: np.ndarray[np.complex_] = np.zeros((n_channels, n_channels), dtype=np.complex_)
            diagonal_indices: np.ndarray[np.int_] = np.vstack((np.arange(n_channels), np.arange(n_channels)), dtype=np.int_)
        elif np.ndim(signal_vectors_for_computation) == 2:  # multiple signal vectors
            matZ_diag: np.ndarray[np.complex_] = np.zeros((np.size(signal_vectors_for_computation, 1), n_channels, n_channels), dtype=np.complex_)
            matD_diag: np.ndarray[np.floating] = np.zeros((np.size(signal_vectors_for_computation, 1), n_channels, n_channels), dtype=np.complex_)
            diagonal_indices: np.ndarray[np.integer] = ImpedanceMatrixGenerator.get_diagonal_indices(signal_vectors_for_computation)
        else:  # This shall not execute
            raise ValueError("If you see this message, the program must have run into some bug.")
        matZ_diag[*diagonal_indices] = np.ravel(matZ_diag_elements_for_computation, order="C")  # Fill diagonal elements  # The first axis (axis=0) changes slowest
        matD_diag_elements_for_computation: np.ndarray[np.floating] = 2 * self._Popt / np.real(matZ_diag_elements_for_computation)
        matD_diag[*diagonal_indices] = np.ravel(matD_diag_elements_for_computation, order="C")
        chunk_39 = self.get_chunk_39(matD_diag, matZ_diag)
        if inverse:
            return linalg.inv(chunk_39), admissibility  # The function shall always return a full vector of admissibility, so that the user can use it to mask pictures
        else:
            return chunk_39, admissibility
        

