class ImpedanceMatrixGenerator:
    """A class that generates the SNR core matrices defined by Equation (39) in Christian Findeklee's "Array Noise Matching--Generalization, Proof and Analogy to Power Matching", IEEE Transactions on Antennas and Propagation, Vol. 59, No. 2, Feb 2011.
       The core matrix is the part between $U_s^H$ and $U_s$.
       The SNR core matrices can be further used for generating SNR maps.
    """

    def __init__(self, antenna_impedance_matrix: np.ndarray, c: np.number = 1., Fopt: np.number = 1., lange_N: np.number = 0., point_coordinates: np.ndarray = None) -> None:
        """Constructs an ImpedanceMatrixGenerator class.

        Args:
            antenna_impedance_matrix (np.ndarray): the antenna array's impedance matrix
            c (np.number, optional): 4 k T B, as defined right below (2). Default to 1. Recommended to be set 1.0 as the term will be a common factor to (39), and it can help the program's numerical accuracy
            Fopt (np.number, optional): the minimal noise figure of preamplifiers, assuming all preamplifiers are the same. Default to 1, or 0 dB noise figure.
            lange_N (np.number, optional): Lange's N of the preamplifiers, assuming all preamplifiers are the same. N = Rn / z_opt ** 2 where F = Fm + Rn / Gs * np.abs(Ys - Yopt) ** 2. Default to 0, i.e., all preamplifiers are noiseless.
            point_coordinates (np.ndarray, optional): point coordinates assembled in an array, of which the dimensions are (# of pixels, 3). Default to None.
        """
        self._c: np.float_ = c
        self._Fopt: np.float_ = Fopt
        self._Popt: np.float_ = lange_N * c
        self._Za: np.ndarray[np.number]= np.copy(antenna_impedance_matrix)  # Makes a copy so that the matrix inside is safe
        self._point_coordinates = np.copy(point_coordinates)
        self._A:  np.ndarray[np.number] = ImpedanceMatrixGenerator.noise_covariance_matrix(self._Za, c, Fopt)  # noise covariance matrix
        if not ImpedanceMatrixGenerator.is_positive_definite(self._A):
            raise ValueError("Antenna noise covariance matrix is not positive definite")
        self._inv_A: np.ndarray[np.number] = linalg.inv(self._A)
        self._diag_D_noise_match: np.ndarray[np.number] = 2 * self._Popt * np.diag(1 / np.diag(np.real(self._Za)))  # diagonal matrix [D] = [2 P_\mathrm{opt;\infty} / R_\mathrm{opt}] for noise match.
        self._diag_Za: np.ndarray[np.number] = np.diag(np.diag(self._Za))
        self._last_diag_Z_elements: np.ndarray[np.number] = None # Temporary storage of diagonal matrix [Z]'s elements defined in (43). All diagonal elements of [Z] will be stored no matter they are admissible or not.
        self._last_signal_vectors: np.ndarray[np.number] = None # Temporary storage of signal vectors
        self._last_signal_vectors_admissible_mask: np.ndarray[np.bool_] = None # Temporary storage of the admissible mask

    @property
    def A(self) -> np.ndarray[np.number]:
        """Returns a copy of matrix A, the noise covariance matrix of the antenna array, supposing purely thermal noise."""
        return np.copy(self._A)  # Returns a copy so that the matrix inside is safe

    @property
    def point_coordinates(self) -> np.ndarray[np.number]:
        """Returns a copy of all point coordinates including inadmissible regions"""
        return np.copy(self._point_coordinates)
    
    @property
    def Za(self) -> np.ndarray[np.number]:
        """Returns a copy of the impedance matrix of the antenna array."""
        return np.copy(self._Za) # Returns a copy so that the matrix inside is safe
    
    @property
    def last_diag_Z_elements(self) -> np.ndarray[np.number]:
        """Returns a copy of the last diagonal elements for SNR optimization at one pixel."""
        return np.copy(self._last_diag_Z_elements)
    
    @staticmethod
    def noise_covariance_matrix(antenna_impedance_matrix: np.ndarray[np.number], c: np.number = 1.0, Fopt: np.number = 1.0) -> np.ndarray[np.number]:
        """Returns the noise covariance matrix of an antenna array, assuming thermal noise only.

        Args:
            antenna_impedance_matrix (np.ndarray[np.number]): the antenna array's impedance matrix. The dimensions should be (# of channels, # of channels)
            c (np.number, optional): 4 k T B, as defined right below (2). Defaults to 1.0.
            Fopt (np.number, optional): the minimal noise figure of preamplifiers, assuming all preamplifiers are the same. Defaults to 1.0, or 0 dB noise figure.

        Returns:
            np.ndarray[np.number]: the noise covariance matrix of an antenna array, assuming thermal noise only 
        """
        # Now only supports cFopt to be a single number
        if antenna_impedance_matrix is None:
            raise ValueError("The antenna array's impedance matrix cannot be None")
        if np.ndim(antenna_impedance_matrix) != 2 or np.size(antenna_impedance_matrix, 0) != np.size(antenna_impedance_matrix, 1):
            raise ValueError("The antenna array's impedance matrix has wrong dimensions")
        return c * Fopt * (antenna_impedance_matrix + antenna_impedance_matrix.conj().T)
    
    @staticmethod
    def is_positive_definite(matP: np.ndarray[np.number]) -> bool:
        """Judges whether a Hermitian matrix is positive definite.

        Args:
            matP (np.ndarray): the Hermitian matrix to check.

        Returns:
            bool: True if the matrix is positive definite, otherwise false.
        """
        return np.all(np.real(linalg.eigvals(matP)) > 0)
    
    @staticmethod
    def get_diagonal_indices(signal_vectors: np.ndarray[np.number]) -> np.ndarray[np.integer]:
        """Generates diagonal indices to put [Z]'s elements by.

        Args:
            signal_vectors (np.ndarray[np.number]): the signal vectors for SNR optimization, stacked as a two-dimensional array of dimensions (# of channels, # of vectors)

        Raises:
            ValueError: when signal_vectors has two or more dimensions.

        Returns:
            np.ndarray[np.integer]: the diagonal indices to put [Z]'s elements by.
        """
        if np.ndim(signal_vectors) > 2:
            raise ValueError("Signal vectors or a bundle of them should only have at most two dimensions")
        n_channel, n_pixels = signal_vectors.shape
        whole_array: np.ndarray[np.integer] = np.array([[x, y, y] for x in range(n_pixels) for y in range(n_channel)], dtype=np.int_)
        return whole_array.T
